    private void refreshTableData() {
    DefaultTableModel model = (DefaultTableModel) eventTable.getModel();
    model.setRowCount(0); // Wipe out old visual rows
    
    // Explicitly reference package to prevent conflicts with java.awt.Event
    List<studentorg.Event> events = eventDAO.getAllEvents();
    for (studentorg.Event e : events) {
        model.addRow(new Object[]{e.getEventId(), e.getOrgId(), e.getEventName(), e.getEventDate()});
    }
}
    

