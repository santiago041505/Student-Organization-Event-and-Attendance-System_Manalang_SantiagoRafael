    private void btnEventAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEventAddActionPerformed
       String orgIdStr = txtOrgId.getText().trim();
    String name = txtEventName.getText().trim();
    String dateStr = txtEventDate.getText().trim();

    // Guardrail validation check
    if (orgIdStr.isEmpty() || name.isEmpty() || dateStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill out all fields before submitting.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        int orgId = Integer.parseInt(orgIdStr);
        // Converts "YYYY-MM-DD" text into a proper SQL Date object
        Date eventDate = Date.valueOf(dateStr); 

        // 0 is passed because Event ID is auto-generated in MySQL
        studentorg.Event newEvent = new studentorg.Event(0, orgId, name, eventDate);
        
        if (eventDAO.addEvent(newEvent)) {
            JOptionPane.showMessageDialog(this, "Event Created Successfully!");
            
            // Reset input boxes
            txtOrgId.setText("");
            txtEventName.setText("");
            txtEventDate.setText("");
            
            // Sync table view with the database update
            refreshTableData();
        }
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Host Org ID must be a numeric ID code.", "Input Error", JOptionPane.ERROR_MESSAGE);
    } catch (IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(this, "Date format must follow YYYY-MM-DD layout.", "Input Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnEventAddActionPerformed

