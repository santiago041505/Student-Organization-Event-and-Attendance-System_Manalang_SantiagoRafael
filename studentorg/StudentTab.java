    private void studentTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_studentTableMouseClicked
        int selectedRow = studentTable.getSelectedRow();
    if (selectedRow != -1) {
        // Map row strings back to text boxes
        String id = studentTable.getValueAt(selectedRow, 0).toString();
        String name = studentTable.getValueAt(selectedRow, 1).toString();
        String course = studentTable.getValueAt(selectedRow, 2).toString();
        
        txtId.setText(id);
        txtName.setText(name);
        txtCourse.setText(course);
    }
    }//GEN-LAST:event_studentTableMouseClicked

