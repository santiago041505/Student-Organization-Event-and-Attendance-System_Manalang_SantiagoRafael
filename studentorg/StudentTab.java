    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String id = txtId.getText().trim();
    String name = txtName.getText().trim();
    String course = txtCourse.getText().trim();

    if (id.isEmpty() || name.isEmpty() || course.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill out all fields before adding.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Student newStudent = new Student(id, name, course);
    if (studentDAO.addStudent(newStudent)) {
        JOptionPane.showMessageDialog(this, "Student Added Successfully!");
        clearFields();
        refreshTableData(studentDAO.getAllStudents()); // Auto-sync table view
    }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String id = txtId.getText().trim();
    String name = txtName.getText().trim();
    String course = txtCourse.getText().trim();

    if (id.isEmpty() || name.isEmpty() || course.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Select a student and complete details to update.", "Validation Error", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Student updatedStudent = new Student(id, name, course);
    if (studentDAO.updateStudent(updatedStudent)) {
        JOptionPane.showMessageDialog(this, "Student Details Updated!");
        clearFields();
        refreshTableData(studentDAO.getAllStudents());
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = studentTable.getSelectedRow();
    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please click a row in the table to select the student to delete.");
        return;
    }
    
    // Snag ID from first column of selected row
    String id = studentTable.getValueAt(selectedRow, 0).toString();
    
    int choice = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to permanently delete student ID: " + id + "?", 
            "Confirm Deletion", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            
    if (choice == JOptionPane.YES_OPTION) {
        if (studentDAO.deleteStudent(id)) {
            JOptionPane.showMessageDialog(this, "Record Deleted.");
            clearFields();
            refreshTableData(studentDAO.getAllStudents());
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

